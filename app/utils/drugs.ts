const byLookupName = new Map<string, string>([
  ...DRUGS.map((drug) => [drug.toLowerCase(), drug] as const),
  ...Object.entries(DRUG_ALIASES).map(
    ([alias, canonical]) => [alias.toLowerCase(), canonical] as const
  ),
]);

// Every canonical drug plus every alias, so typing "Tyl" or "Coartem" finds
// something. Selecting an alias stores the canonical name, which is what
// resolveDrugName below is for.
const drugOptions = [...DRUGS, ...Object.keys(DRUG_ALIASES)]
  .sort((a, b) => a.localeCompare(b))
  .map((drug) => ({ id: drug, name: drug }));

/** The list the drug field offers. Stable across calls -- see the note above. */
export const getDrugOptions = () => drugOptions;

/**
 * The name to store for what was typed, or undefined if nothing is known by it.
 *
 * Case and surrounding space are ignored, so one drug is never filed under two
 * spellings. Undefined is not a rejection: the caller keeps the typed name, which
 * is how a mission records something neither list has heard of.
 */
export const resolveDrugName = (typed?: string) =>
  byLookupName.get((typed ?? "").trim().toLowerCase());
