/**
 * The drugs a mission prescribes, and the other names people call them by.
 *
 * Two lists, and the distinction matters. DRUGS is what the field offers and what
 * gets stored: one canonical name per molecule. DRUG_ALIASES is everything else a
 * clinician might type for the same thing -- a brand, or the name used on the
 * other side of the Atlantic -- which resolves to the canonical name on the way
 * in. A mission still carries drugs neither list knows, and those go in exactly
 * as typed; see DrugSelector.
 *
 * Why aliases at all: the medication report groups by the stored name, so every
 * spelling of one molecule is a separate row in it. Before this, Paracetamol,
 * Acetaminophen and Tylenol split 71 prescriptions of the same drug three ways,
 * and the first two split because the list offered both.
 *
 * Paracetamol is the canonical one: it is the international nonproprietary name,
 * and it was already the majority spelling in this database. Anyone who types
 * Acetaminophen or Tylenol still finds it -- the row simply reads Paracetamol.
 *
 * What is not here is as deliberate as what is. The list was 444 entries carrying
 * CAR-T therapy, withdrawn COVID antibodies, IV anaesthetics, clotting factors
 * and forty cytotoxics -- none of which a field clinic dispenses, and all of
 * which the near-match search had to compete against. Of those 444, 44 had ever
 * been used. Pruning them is what makes room for the drugs that were missing:
 * metformin, aspirin, cephalexin, salbutamol, ORS, artemether/lumefantrine,
 * and -- for the dentistry this app was built around -- articaine and
 * chlorhexidine.
 *
 * Built once at module scope rather than per call: a fresh array each time would
 * invalidate the memo that decides which drugs the autocomplete shows, so the
 * near-match search would rerun on every keystroke.
 */

